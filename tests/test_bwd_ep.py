"""Backward models (simul_backward_model and relatives) and the extended path against Dynare 7.2 run under Octave 8.4
(reference/oo/<case>.mat, regenerated by reference/oo/r_bwd.m)."""
import shutil
from pathlib import Path

import numpy as np
import pytest
from scipy.io import loadmat

import pydyn
from pydyn import ResultsError
from pydyn.extended_path_stoch import gauss_hermite, integration_nodes

import test_results as T

REF = Path(__file__).resolve().parent.parent / "reference" / "oo"
CASES = ["bwd_nl", "bwd_lin", "bwd_aux", "bwd_aux14", "bwd_irf", "bwd_fc", "ep_back", "ep_rbc", "ep_sep"]
#: bwd_aux14 solves with solve_algo 14 and 12 (block trust region): Dynare's MEX block solver stops at its tolerance on the
#: residuals (1e-5) and pydyn's iterates differ from it by 4e-5 in the levels (Dynare's own algorithms 4 and 14 differ by
#: 1.8e-4 on the same model).
TOL = {"bwd_aux14": 1e-4}


@pytest.fixture(scope="module")
def runs(tmp_path_factory):
    d = tmp_path_factory.mktemp("bwd")
    out = {}
    for c in CASES:
        shutil.copy(REF / f"{c}.mod", d / f"{c}.mod")
        shutil.copy(REF / "fsdat_simul.m", d / "fsdat_simul.m")
        out[c] = pydyn.dynare(d / f"{c}.mod")
    return out


@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("var", ["oo_", "M_"])
def test_against_octave(runs, case, var):
    ref = loadmat(REF / f"{case}.mat", struct_as_record=True)[var]
    out = []
    T._diff(ref, getattr(runs[case], var), var, out, TOL.get(case, 1e-6))
    assert not out, out


@pytest.mark.parametrize("case", CASES)
def test_matlab_variables(runs, case):
    ref = loadmat(REF / f"{case}.mat", struct_as_record=True)
    ws = runs[case].vars
    names = [n for n in ref if not n.startswith("__") and n not in ("M_", "oo_", "options_", "ans", "info")]
    out = []
    for n in names:
        if n not in ws:
            if n not in ("tic0", "bayestopt_", "dataset_", "dataset_info", "estim_params_", "estimation_info"):
                out.append((n, "missing"))
            continue
        r = ref[n]
        if r.dtype.names or r.dtype == object or r.dtype.kind == "U":
            continue
        T._diff(r, ws[n], n, out, TOL.get(case, 1e-6))
    assert not out, out


def test_gauss_hermite():
    nodes, w = gauss_hermite(5)
    assert abs(w.sum() - 1) < 1e-12
    assert np.allclose(nodes / np.sqrt(2), [-2.020182870, -0.9585724646, 0, 0.9585724646, 2.020182870], atol=1e-8)
    nodes, w = integration_nodes("Tensor-Gaussian-Quadrature", 3, np.diag([0.1, 0.2]))
    assert nodes.shape == (9, 2) and abs(w.sum() - 1) < 1e-12
    assert np.allclose(w @ nodes**2, [0.01, 0.04])
    nodes, w = integration_nodes("Unscented", 0, np.diag([0.1, 0.2]))
    assert nodes.shape == (5, 2) and abs(w.sum() - 1) < 1e-12 and np.allclose(w @ nodes**2, [0.01, 0.04])


def _run(tmp_path, body_after_model, name="t"):
    src = (REF / "ep_rbc.mod").read_text()
    head = src[:src.index("extended_path(periods=30);")]
    (tmp_path / f"{name}.mod").write_text(head + body_after_model)
    return pydyn.dynare(tmp_path / f"{name}.mod")


def test_sparse_tree_and_hybrid_are_refused(tmp_path):
    with pytest.raises(ResultsError, match="sparse tree"):
        _run(tmp_path, "extended_path(periods=2, order=1, tree=sparse, solver_periods=20);\n")
    with pytest.raises(ResultsError, match="hybrid"):
        _run(tmp_path, "extended_path(periods=2, order=1, hybrid, solver_periods=20);\n")


def test_stochastic_path_on_a_backward_model_is_an_error(tmp_path):
    src = (REF / "ep_back.mod").read_text().replace(
        "extended_path(order=0, periods=40);",
        "options_.ep.stochastic.order = 1;\n[ts, oo_] = extended_path([], 5, [], options_, M_, oo_);")
    (tmp_path / "b.mod").write_text(src)
    with pytest.raises(ResultsError, match="purely backward"):
        pydyn.dynare(tmp_path / "b.mod")


def test_extended_path_needs_periods(tmp_path):
    with pytest.raises(RuntimeError, match="'periods' option of 'extended_path' is mandatory"):
        _run(tmp_path, "extended_path(order=0);\n")


def test_delete_only_removes_files_written_by_pydyn(tmp_path):
    (tmp_path / "keep.mat").write_bytes(b"not ours")
    mod = (REF / "ep_back.mod").read_text().replace(
        "extended_path(order=0, periods=40);",
        "extended_path(order=0, periods=5);\nSimulated_time_series.save('mine');\ndelete mine.mat\n")
    (tmp_path / "d.mod").write_text(mod)
    pydyn.dynare(tmp_path / "d.mod")
    assert not (tmp_path / "mine.mat").exists()
    (tmp_path / "e.mod").write_text(mod.replace("delete mine.mat", "delete keep.mat"))
    with pytest.raises(ResultsError, match="was not written by pydyn"):
        pydyn.dynare(tmp_path / "e.mod")
    assert (tmp_path / "keep.mat").exists()


def test_dseries_save_and_read_round_trip(tmp_path):
    mod = (REF / "ep_back.mod").read_text().replace(
        "extended_path(order=0, periods=40);",
        "extended_path(order=0, periods=5);\nSimulated_time_series.save('rt');\nds = dseries('rt.mat');\n"
        "same = max(max(abs(ds.data - Simulated_time_series.data)));\nnames_ok = isequal(ds.name, Simulated_time_series.name);\n")
    (tmp_path / "r.mod").write_text(mod)
    ws = pydyn.dynare(tmp_path / "r.mod")
    assert float(ws.vars["same"]) == 0.0
