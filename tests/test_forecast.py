def test_conditional_forecast_explicit_paths_and_errors(tmp_path):
    m = _load(tmp_path, "fc_cf_nk", ["-DVARIANT=1"], tag="cfe")
    base = dict(parameter_set="calibration", controlled_varexo=["ea", "er"], periods=4, replic=30, conf_sig=0.8)
    out = F.conditional_forecast(m, {"yobs": [0.4, 0.4], "robs": [2.5, np.nan]}, rng=1, **base)
    close(out.cond["Mean"]["yobs"][1:3], [0.4, 0.4], "path", rtol=1e-9, atol=1e-9)
    assert out.cond["Mean"]["robs"].shape == (5,) and out.cond["ci"]["robs"].shape == (2, 5)
    with pytest.raises(ValueError, match="number of constrained variables"):
        F.conditional_forecast(m, {"yobs": [0.4]}, **base)
    with pytest.raises(ValueError, match="not a shock"):
        F.conditional_forecast(m, {"yobs": [0.4], "robs": [2.0]}, **{**base, "controlled_varexo": ["ea", "nope"]})
    with pytest.raises(ValueError, match="periods"):
        F.conditional_forecast(m, {"yobs": [0.4] * 6, "robs": [2.0] * 6}, **base)


