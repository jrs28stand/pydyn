"""Forecasts against Dynare 7.2 under Octave 8.4 (reference/forecast/*.mod, results in reference/forecast/*.mat,
regenerated by reference/forecast/r_forecast.m and r_fc_post.m):

* ``forecast`` after ``stoch_simul`` (orders 1 to 3, ``varexo_det``, ``histval``, measurement error); the simulated
  bands of orders 2 and 3 replay Dynare's ``randn('state', seed)`` draws through ``pydyn.octave_rng``;
* ``estimation(forecast=N)`` at the mode (trends, prefilter, diffuse filter, missing data, loglinear);
* the posterior forecast distribution (``oo_.MeanForecast``, ``PointForecast``, ``PointForecastME``) over sub-draws;
* ``conditional_forecast`` with paths, controlled shocks, parameter sets, observation trends.
Accuracy is rounding (1e-12 here against 1e-14 or better observed)."""
import os
import shutil
import warnings
from pathlib import Path

import numpy as np
import pytest
from scipy.io import loadmat

import pydyn
from pydyn import estimation, forecast as F
from pydyn.octave_rng import OctaveRandom

ROOT = Path(__file__).resolve().parent.parent
REFROOT = Path(os.environ.get("PYDYN_REF", str(ROOT / "reference")))
REF = REFROOT / "forecast"

try:
    pydyn.korder.load_library()
    HAVE_LIB = True
except FileNotFoundError:
    HAVE_LIB = False

needs_korder = pytest.mark.skipif(not HAVE_LIB, reason="k-order library not available")

pytestmark = pytest.mark.filterwarnings("ignore")

DATA = ["est_nk_data.m", "est_nk_miss.m", "est_ur_data.m", "est_ur_miss.m", "est_schorfheide_data.m", "post_nk_mode0.mat"]


def _load(tmp_path, mod, args=(), tag=None):
    d = tmp_path / (tag or mod)
    d.mkdir(exist_ok=True)
    shutil.copy(REF / f"{mod}.mod", d)
    for f in DATA:
        if (REFROOT / f).exists():
            shutil.copy(REFROOT / f, d)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return pydyn.Model(pydyn.run_preprocessor(d / f"{mod}.mod", extra_args=tuple(args)))


def _mat(name):
    return loadmat(REF / f"{name}.mat", squeeze_me=True, struct_as_record=False)


def close(a, b, what, rtol=1e-11, atol=1e-12):
    a, b = np.asarray(a, float), np.asarray(b, float)
    assert a.shape == b.shape, (what, a.shape, b.shape)
    assert not np.isnan(a).any() and not np.isnan(b).any(), what
    np.testing.assert_allclose(a, b, rtol=rtol, atol=atol, err_msg=what)


def same_fields(got, ref, what, fields=("Mean", "HPDinf", "HPDsup", "HPDinf_ME", "HPDsup_ME", "Exogenous")):
    for fld in fields:
        g = getattr(got, fld)
        r = getattr(ref, fld, None)
        if r is None or not hasattr(r, "_fieldnames"):
            assert not g, (what, fld, list(g))
            continue
        assert set(g) == set(r._fieldnames), (what, fld, set(g), r._fieldnames)
        for v in g:
            close(g[v], getattr(r, v), f"{what}.{fld}.{v}")


