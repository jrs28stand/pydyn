    same_fields(F.forecast(m, ["y", "c", "k"], periods=6, conf_sig=0.95, **kw), r["fc4"], "fc4")             # with measurement error
    out = F.forecast(m, ["y", "c", "k"], periods=6, conf_sig=0.95, **kw)
    assert set(out.Exogenous) == {"ahat", "bhat"} and len(out.Exogenous["bhat"]) == 6


