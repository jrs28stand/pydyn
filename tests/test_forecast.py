def _estimate_args(case, variant):
    return [f"-DVARIANT={variant}"]


@pytest.mark.parametrize("case,variant", EST_CASES)
def test_forecast_from_smoothed_state(tmp_path, case, variant):
    """Mean and bands (with measurement error) from the end-of-sample smoothed state, at Dynare's parameter vector
    (posterior mode, ML mode or the initial values): observation trends, prefilter, diffuse filter, missing data."""
    m = _load(tmp_path, case, _estimate_args(case, variant), tag=f"{case}_{variant}")
    r = _mat(f"{case}_{variant}")
    est = estimation.Estimation(m)
    xp = np.atleast_1d(r["xp"]).astype(float)
    theta = xp if xp.size else np.asarray(est.x0, float)
    vl = ['yobs', 'piobs', 'robs', 'y'] if variant == 11 else None        # prefilter: the list must hold every observable
    out = F.forecast_at(m, est, theta, var_list=vl, shift_bands=False)
    assert out.task == "smoother" and out.periods == 6
    same_fields(out, r["fc"], f"{case}_{variant}")
    assert np.isfinite(out.Mean["yobs" if case == "fc_est_nk" else "xobs"]).all()


