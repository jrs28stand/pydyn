@pytest.mark.parametrize("tag,post,variant", [("p7", 7, 0), ("p8_9", 8, 9)])
def test_posterior_forecast_replays_dynares_draws(tmp_path, tag, post, variant):
    """``prior_posterior_statistics('posterior', ...)`` with ``forecast=6`` over 25-30 sub-draws: the parameter
    vectors and the random numbers (``randn('state', 77)``) are replayed, so every statistic of MeanForecast,
    PointForecast and PointForecastME (mean, median, variance, HPD limits, deciles) agrees. The second case has
    correlated measurement errors."""
    m = _load(tmp_path, "fc_post_nk", [f"-DPOST={post}", f"-DVARIANT={variant}"], tag=tag)
    r = _mat(f"fc_post_{tag}")
    est = estimation.Estimation(m)
    h = int(r["horizon"])
    pf = F.posterior_forecast(est, params=np.atleast_2d(r["params"]), rng=OctaveRandom(77), horizon=h,
                              mh_conf_sig=float(r["mh_conf_sig"]))
    assert pf.horizon == h and pf.draws == np.atleast_2d(r["params"]).shape[0]
    for name in ("MeanForecast", "PointForecast", "PointForecastME"):
        got, ref = getattr(pf, name), r[name]
        for stat in ("Mean", "Median", "Var", "HPDinf", "HPDsup", "deciles"):
            rs = getattr(ref, stat)
            assert set(got[stat]) == set(rs._fieldnames), (name, stat)
            for v in got[stat]:
                a, b = np.asarray(got[stat][v], float), np.asarray(getattr(rs, v), float)
                if stat == "deciles":
                    assert a.shape == (9, h)
                close(a, b, f"{tag}.{name}.{stat}.{v}", rtol=1e-10, atol=1e-11)
    # the point forecast adds shock uncertainty to the mean forecast
    assert np.all(pf.PointForecast["Var"]["y"] > pf.MeanForecast["Var"]["y"] - 1e-12)


# ---------------------------------------------------------------------------------------------------- conditional forecasts
def _cf_check(out, r, what):
    cf = r["cf"]
    for grp, ob in (("cond", out.cond), ("uncond", out.uncond)):
        for fld in ("Mean", "ci"):
            ref = getattr(getattr(cf, grp), fld)
            assert set(ob[fld]) == set(ref._fieldnames), (what, grp, fld)
            for v in ob[fld]:
                close(ob[fld][v], getattr(ref, v), f"{what}.{grp}.{fld}.{v}", rtol=1e-10, atol=1e-11)
    for fld in ("Mean", "ci"):
        ref = getattr(cf.controlled_exo_variables, fld)
        assert set(out.controlled_exo_variables[fld]) == set(ref._fieldnames)
        for v in ref._fieldnames:
            close(out.controlled_exo_variables[fld][v], getattr(ref, v), f"{what}.exo.{fld}.{v}", rtol=1e-10, atol=1e-11)
    assert list(out.instruments) == list(np.atleast_1d(cf.instruments))
    np.testing.assert_array_equal(out.controlled_variables_index + 1, np.atleast_1d(cf.controlled_variables))


@pytest.mark.parametrize("variant,kind", [(0, "mode"), (1, "calibration"), (2, "prior_mean"), (3, "mode")])
def test_conditional_forecast_replays_dynares_draws(tmp_path, variant, kind):
    """Paths on yobs and robs controlled by shocks, 250-300 replications replayed from ``randn('state', 77)``:
    posterior mode (full and gapped paths, correlated shocks: Cholesky), calibration after ``stoch_simul`` and the
    prior mean. Means, bands of both forecasts and the controlled shocks agree to rounding."""
    m = _load(tmp_path, "fc_cf_nk", [f"-DVARIANT={variant}"], tag=f"cf{variant}")
    r = _mat(f"fc_cf_nk_{variant}")
    kw = {}
    if kind != "calibration":
        kw["estimation"] = estimation.Estimation(m)
    if kind == "mode":
        kw["theta"] = np.atleast_1d(r["xp"]).astype(float)
    out = F.conditional_forecast(m, rng=OctaveRandom(77), **kw)       # paths, shocks, periods, replic from the .mod file
    _cf_check(out, r, f"cf{variant}")
    assert out.controlled_variables == ["yobs", "robs"]
    # the controlled variables sit on their paths in every draw's mean (to the path's NaN gaps)
    for k, v in enumerate(out.controlled_variables):
        p = out.paths[k]
        ok = np.isfinite(p)
        close(out.cond["Mean"][v][1:1 + len(p)][ok], p[ok], f"path {v}", rtol=1e-9, atol=1e-9)


