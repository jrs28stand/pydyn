"""pydyn.dynare(): M_, options_ and oo_ against Dynare 7.2 run under Octave 8.4 (reference/oo/*.mat).

The cases (reference/oo/<case>.mod, regenerated by reference/oo/r_oo.m) run MATLAB lines that read and
write the structs between commands.  Every field Octave fills must be present with Octave's shape and
value, or refused (a documented field pydyn does not fill); nothing may differ."""
import shutil
import sys
from pathlib import Path

import numpy as np
import pytest
from scipy.io import loadmat

import pydyn
from pydyn import ResultsError
from pydyn.results_m import known_missing
from pydyn.matlab import Cell, Struct, Tainted, Unsupported

REF = Path(__file__).resolve().parent.parent / "reference" / "oo"
CASES = ["rbc_oo", "rbc_oo_o2", "rbc_oo_o3", "rbc_oo_pf", "rbc_oo_loop", "rbc_oo_pfloop"]

# Fields that are wall-clock time or a dseries object, or that pydyn refuses (see the test below).
SKIP = {"oo_.time", "oo_.initval_series", "M_.aux_vars"}
REFUSED = {"oo_.dr.fuu", "oo_.dr.g_0", "oo_.dr.g_1", "oo_.dr.g_2", "oo_.dr.g_3", "oo_.dr.pruning"}


def _diff(ref, ours, path, out, tol):
    if path in SKIP:
        return
    if isinstance(ref, np.ndarray) and ref.dtype.names:
        if not isinstance(ours, Struct):
            out.append((path, "not a struct"))
            return
        for n in ref.dtype.names:
            p = f"{path}.{n}"
            if p in REFUSED or p in SKIP:
                continue
            if n not in ours:
                if not (path == "M_" and known_missing(n)):      # M_ fields refused by name (see results_m)
                    out.append((p, "missing"))
                continue
            r = ref[n].ravel()[0] if ref[n].size == 1 else ref[n]
            _diff(r, ours[n], p, out, tol)
        for n in ours:
            if n not in ref.dtype.names and f"{path}.{n}" not in SKIP:
                out.append((f"{path}.{n}", "extra"))
        return
    if isinstance(ref, np.ndarray) and ref.dtype == object:
        if not isinstance(ours, Cell) or tuple(ours.shape) != ref.shape:
            out.append((path, "cell shape"))
            return
        for i, (a, b) in enumerate(zip(ref.ravel(order="F"), ours.items)):
            _diff(a, b, f"{path}{{{i}}}", out, tol)
        return
    if isinstance(ref, np.ndarray) and ref.dtype.kind == "U":
        if "".join(ref.ravel()) != ours:
            out.append((path, "string"))
        return
    if isinstance(ours, (str, Cell, Struct, Tainted)):
        out.append((path, "type"))
        return
    a, b = np.asarray(ref, float), np.asarray(ours, float)
    a = a.reshape(1, -1) if a.ndim < 2 else a
    b = b.reshape(1, 1) if b.ndim == 0 else (b.reshape(1, -1) if b.ndim < 2 else b)
    if a.shape != b.shape:
        out.append((path, f"shape {a.shape} vs {b.shape}"))
        return
    if path.endswith("dr.eigval"):                 # the sign of an infinite eigenvalue is rounding noise in Dynare
        a, b = np.where(np.isinf(a), np.inf, a), np.where(np.isinf(b), np.inf, b)
    same = (np.isnan(a) & np.isnan(b)) | (a == b)
    d = np.abs(a - b)
    bad = ~same & ~(d <= tol * np.maximum(1.0, np.abs(a)))
    if bad.any():
        out.append((path, f"value, max abs {np.nanmax(d[bad]):.3g}"))


@pytest.fixture(scope="module")
def runs(tmp_path_factory):
    d = tmp_path_factory.mktemp("oo")
    out = {}
    for c in CASES:
        shutil.copy(REF / f"{c}.mod", d / f"{c}.mod")
        out[c] = pydyn.dynare(d / f"{c}.mod")
    return out


@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("var", ["oo_", "M_"])
def test_against_octave(runs, case, var):
    ref = loadmat(REF / f"{case}.mat", struct_as_record=True)[var]
    out = []
    # simulated paths agree to the steady-state tolerance (Dynare stops its Newton iterations at 1e-5)
    _diff(ref, getattr(runs[case], var), var, out, 1e-6)
    assert not out, out


@pytest.mark.parametrize("case", CASES)
def test_matlab_variables(runs, case):
    ref = loadmat(REF / f"{case}.mat", struct_as_record=True)
    ws = runs[case].vars
    names = [n for n in ref if not n.startswith("__") and n not in ("M_", "oo_", "options_", "ans", "info")]
    out = []
    for n in names:
        if n in ("oo_", "M_", "options_", "i", "s", "dynareOBC") or n not in ws:
            continue
        r = ref[n]
        if r.dtype.names or r.dtype == object or r.dtype.kind == "U":
            continue
        _diff(r, ws[n], n, out, 1e-6)
    assert not out, out


def test_refused_field_is_refused_not_wrong(tmp_path):
    """oo_.dr.fuu is filled by Dynare at order 2 and not by pydyn: reading it is a refusal, never a wrong value."""
    (tmp_path / "e.mod").write_text((REF / "rbc_oo_o2.mod").read_text() + "\nzz = oo_.dr.fuu;\n")
    with pytest.raises(ResultsError, match="fuu"):
        pydyn.dynare(tmp_path / "e.mod")


def test_unknown_field_is_an_error(tmp_path):
    (tmp_path / "e.mod").write_text((REF / "rbc_oo.mod").read_text() + "\nzz = oo_.no_such_field;\n")
    with pytest.raises(ResultsError):
        pydyn.dynare(tmp_path / "e.mod")


def test_self_check_error_propagates(tmp_path):
    (tmp_path / "e.mod").write_text((REF / "rbc_oo.mod").read_text()
                                    + "\nif abs(oo_.dr.ghx(1,1)) > 0, error('self check failed'); end\n")
    with pytest.raises(ResultsError, match="self check failed"):
        pydyn.dynare(tmp_path / "e.mod")


def test_model_api_unchanged():
    assert "run_statements" in pydyn.Model.__init__.__code__.co_varnames
