"""docs/ACCEPTANCE.md from the per-file results of tools/accept_sweep.py (see there)."""
import collections
import json
import re
from pathlib import Path

ORDER = ["match", "partial", "refused", "wrong", "pydyn-error", "dynare-failed", "xfail", "no-comparison"]


def normalise(msg):
    m = re.sub(r"^[\w.]+: ", "", msg.strip())
    m = re.sub(r"'[^']*'|\"[^\"]*\"", "'..'", m)
    m = re.sub(r"\b\d+(\.\d+)?(e[+-]?\d+)?\b", "N", m)
    return m[:140]


def report(ref, out):
    ref = Path(ref)
    known = {}
    kf = Path(__file__).with_name("accept_known.json")
    if kf.exists():
        known = json.loads(kf.read_text())
    res = []
    for f in sorted((ref / "_pydyn").rglob("*.json")):
        res.append(json.loads(f.read_text()))
    octave = collections.Counter()
    for f in sorted(ref.rglob("*.json")):
        if any(p.startswith("_") for p in f.relative_to(ref).parts):
            continue
        octave[json.loads(f.read_text())["status"]] += 1
    byv = collections.Counter(r["verdict"] for r in res)
    folder = collections.defaultdict(collections.Counter)
    for r in res:
        parts = r["file"].split("/")
        folder[parts[0] if len(parts) > 1 else "(root)"][r["verdict"]] += 1
    L = []
    L.append("# Acceptance sweep: Dynare 7.2 test suite against pydyn\n")
    L.append("Generated by `python tools/accept_sweep.py report` from the results of `tools/accept_octave.py` (Dynare 7.2 under Octave 8.4) and "
             "`tools/accept_sweep.py run` (pydyn). Method, tolerances and verdict definitions: see the docstring of `tools/accept_sweep.py`.\n")
    L.append("## Octave runs of Dynare (the reference)\n")
    L.append("| status | files |\n|---|---|")
    for k, v in octave.most_common():
        L.append(f"| {k} | {v} |")
    L.append("\n`dynare-error` includes tests the Octave build cannot run (graphics, missing toolboxes); `xfail` are Dynare's own expected failures.\n")
    L.append("## pydyn verdicts\n")
    L.append("| verdict | files |\n|---|---|")
    for k in ORDER:
        L.append(f"| {k} | {byv.get(k, 0)} |")
    L.append(f"| **total** | {len(res)} |\n")
    L.append("match: every compared field agrees and none is missing; partial: some agree, others are not produced or refused; refused: pydyn "
             "raises its Unsupported/NotImplemented style error; wrong: a compared field differs beyond tolerance; pydyn-error: unexpected exception; "
             "no-comparison: pydyn loads the model but the stored run has no field the sweep can compare.\n")
    L.append("## By test folder\n")
    L.append("| folder | " + " | ".join(ORDER) + " | total |\n|---|" + "---|" * (len(ORDER) + 1))
    for fo in sorted(folder):
        c = folder[fo]
        L.append(f"| {fo} | " + " | ".join(str(c.get(k, 0)) for k in ORDER) + f" | {sum(c.values())} |")
    L.append("")
    # wrong
    wrong = [r for r in res if r["verdict"] == "wrong"]
    L.append(f"## Wrong results ({len(wrong)} files)\n")
    L.append("| file | field(s) and size of difference | classification |\n|---|---|---|")
    for r in wrong:
        bad = "; ".join(f"`{x[0]}` {x[2]}" for x in r["rows"] if x[1] == "wrong")[:300]
        k = known.get(r["file"], {})
        L.append(f"| {r['file']} | {bad} | {k.get('class', 'not yet investigated')}: {k.get('note', '')} |")
    L.append("")
    err = [r for r in res if r["verdict"] == "pydyn-error"]
    L.append(f"## Unexpected pydyn errors ({len(err)} files)\n")
    c = collections.Counter(normalise(r["detail"].split(";")[0]) for r in err)
    for k, v in c.most_common(25):
        L.append(f"- {v} x {k}")
    L.append("")
    ref_ = [r for r in res if r["verdict"] in ("refused", "partial")]
    L.append("## Commonest refusal / not-produced reasons\n")
    cc = collections.Counter()
    for r in ref_:
        seen = set()
        for x in r["rows"]:
            if x[1] in ("refused", "not-produced"):
                key = normalise(f"{x[0].split('.')[0]}: {x[2]}") if x[1] == "refused" else f"not produced: oo_.{x[0].split('.')[0]}"
                seen.add(key)
        if r["verdict"] == "refused" and r["detail"].startswith("load:"):
            seen.add(normalise(r["detail"]))
        for s in seen:
            cc[s] += 1
    for k, v in cc.most_common(30):
        L.append(f"- {v} files: {k}")
    L.append("")
    # field statistics
    fs = collections.defaultdict(collections.Counter)
    for r in res:
        for x in r["rows"]:
            fs[re.sub(r"\.[A-Za-z0-9_]+_[A-Za-z0-9_]+$", "", x[0]) if x[0].startswith("irfs.") else x[0].split(".")[0] if x[0].startswith(("Smoothed", "Updated", "Filtered", "posterior", "mle")) else x[0]][x[1]] += 1
    L.append("## Field statistics (rows over all files)\n")
    L.append("| oo_ field | match | wrong | not-produced | refused | skipped | error |\n|---|---|---|---|---|---|---|")
    for k in sorted(fs):
        c = fs[k]
        L.append(f"| {k} | {c['match']} | {c['wrong']} | {c['not-produced']} | {c['refused']} | {c['skipped']} | {c['error']} |")
    Path(out).write_text("\n".join(L) + "\n")
    print("wrote", out)
